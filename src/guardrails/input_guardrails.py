# Quyết định rõ ràng — tránh đảo nghĩa True/False
InputStatus = Literal["ALLOW", "BLOCK"]


def _normalize(text: str) -> str:
    """Canonicalize: NFKC, drop invisible/format chars, strip accents, collapse spaces."""
    text = unicodedata.normalize("NFKC", text or "")
    text = "".join(c for c in text if unicodedata.category(c) not in ("Cf", "Cc") or c in "\n\t ")
    text = unicodedata.normalize("NFD", text).replace("đ", "d").replace("Đ", "D")
    text = "".join(c for c in text if unicodedata.category(c) != "Mn")
    return re.sub(r"\s+", " ", text).strip().lower()


def _has_term(text: str, term: str) -> bool:
    return re.search(rf"\b{re.escape(term)}", text) is not None


# ============================================================
# Implement detect_injection()
#
# Canonicalize Unicode/invisible spacing, then detect prompt injection.
# Return ``"BLOCK"`` if injection is detected, else ``"ALLOW"``.
#
# Required cases:
# - "ignore (all )?(previous|above) instructions"
# - "you are now"
# - "system prompt"
# - "reveal your (instructions|prompt)"
# - "pretend you are"
# - "act as (a |an )?unrestricted"
# Also handle an instruction embedded in an untrusted email/RAG document, e.g.
# ``Ignore\u200b all previous instructions``. Do not block a benign request to
# summarize an external bank-transfer email just because it is external data.
# Regex is one signal, not the whole security boundary.
# ============================================================

def detect_injection(user_input: str) -> InputStatus:
    """Detect prompt injection patterns in user input.

    Args:
        user_input: The user's message

    Returns:
        ``"BLOCK"`` if injection detected (chặn), ``"ALLOW"`` otherwise (cho qua).
    """
    text = _normalize(user_input)

    INJECTION_PATTERNS = [
        # TODO: Add at least 5 regex patterns
        # Example:
        # r"ignore (all )?(previous|above) instructions",
        r"ignore\s+(?:all\s+|any\s+|the\s+|your\s+)*(?:previous\s+|prior\s+|above\s+|earlier\s+|system\s+)*(?:instructions?|rules|directives|guidelines)",
        r"(?:disregard|forget|override|bypass)\s+(?:all\s+|any\s+|the\s+|your\s+)*(?:previous\s+|prior\s+|above\s+|earlier\s+)*(?:instructions?|rules|guidelines|safety)",
        r"\byou\s+are\s+now\b",
        r"system\s*prompt",
        r"reveal\s+(?:me\s+)?(?:your|the)\s+(?:hidden\s+|secret\s+|initial\s+)?(?:instructions?|prompt|rules|configuration)",
        r"(?:show|print|repeat|output|leak)\s+(?:me\s+)?(?:your|the)\s+(?:hidden\s+|initial\s+)?(?:instructions?|prompt)",
        r"pretend\s+(?:you\s+are|to\s+be|you're)",
        r"act\s+as\s+(?:a\s+|an\s+)?(?:unrestricted|unfiltered|jailbroken|dan\b)",
        r"\b(?:jailbreak|developer\s+mode|dan\s+mode|do\s+anything\s+now)\b",
        r"without\s+(?:any\s+)?(?:restrictions|filters|safety|guardrails)",
        # Vietnamese (đã bỏ dấu qua _normalize)
        r"bo\s+qua\s+(?:moi\s+|tat\s+ca\s+)?(?:cac\s+)?(?:huong\s+dan|chi\s+dan|quy\s+tac)",
        r"tiet\s+lo\s+(?:system\s+prompt|huong\s+dan\s+he\s+thong|mat\s+khau)",
        r"gia\s+vo\s+(?:ban\s+)?la",
    ]

    for pattern in INJECTION_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return "BLOCK"
    return "ALLOW"


# ============================================================
# Implement topic_filter()
#
# Check if user_input belongs to allowed topics.
# The VinBank agent should only answer about: banking, account,
# transaction, loan, interest rate, savings, credit card.
#
# Return ``"BLOCK"`` if input should be blocked (off-topic / blocked topic).
# Return ``"ALLOW"`` if banking-related and OK.
# ============================================================

def topic_filter(user_input: str) -> InputStatus:
    """Decide whether the input is on-topic for VinBank.

    Args:
        user_input: The user's message

    Returns:
        ``"BLOCK"`` = chặn (off-topic hoặc topic cấm).
        ``"ALLOW"`` = cho qua (câu banking hợp lệ).
    """
    input_lower = _normalize(user_input)

    # TODO: Implement logic:
    # 1. If input contains any blocked topic -> return "BLOCK"
    # 2. If input doesn't contain any allowed topic -> return "BLOCK"
    # 3. Otherwise -> return "ALLOW"

    if any(_has_term(input_lower, _normalize(t)) for t in BLOCKED_TOPICS):
        return "BLOCK"
    if not any(_has_term(input_lower, _normalize(t)) for t in ALLOWED_TOPICS):
        return "BLOCK"
    return "ALLOW"


# ============================================================
# Implement InputGuardrailPlugin
#
# This plugin blocks bad input BEFORE it reaches the LLM.
# Fill in the on_user_message_callback method.
#
# NOTE: The callback uses keyword-only arguments (after *).
#   - user_message is types.Content (not str)
#   - Return types.Content to block, or None to pass through
# ============================================================

class InputGuardrailPlugin(base_plugin.BasePlugin):
    """Plugin that blocks bad input before it reaches the LLM."""

    def __init__(self):
        super().__init__(name="input_guardrail")
        self.blocked_count = 0
        self.total_count = 0

    def _extract_text(self, content: types.Content) -> str:
        """Extract plain text from a Content object."""
        text = ""
        if content and content.parts:
            for part in content.parts:
                if hasattr(part, "text") and part.text:
                    text += part.text
        return text

    def _block_response(self, message: str) -> types.Content:
        """Create a Content object with a block message."""
        return types.Content(
            role="model",
            parts=[types.Part.from_text(text=message)],
        )

    async def on_user_message_callback(
        self,
        *,
        invocation_context: InvocationContext,
        user_message: types.Content,
    ) -> types.Content | None:
        """Check user message before sending to the agent.

        Returns:
            None if message is safe (let it through),
            types.Content if message is blocked (return replacement)
        """
        self.total_count += 1
        text = self._extract_text(user_message)

        # TODO: Implement logic:
        # 1. Call detect_injection(text)
        #    - If "BLOCK": increment blocked_count, return self._block_response("...")
        # 2. Call topic_filter(text)
        #    - If "BLOCK": increment blocked_count, return self._block_response("...")
        # 3. If both return "ALLOW": return None (let message through)

        if detect_injection(text) == "BLOCK":
            self.blocked_count += 1
            return self._block_response(
                "Request blocked: possible prompt injection detected. "
                "I can only help with VinBank banking questions."
            )
        if topic_filter(text) == "BLOCK":
            self.blocked_count += 1
            return self._block_response(
                "Sorry, I can only help with banking topics "
                "(accounts, transfers, loans, savings, credit cards)."
            )
        return None


